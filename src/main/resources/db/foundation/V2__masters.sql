CREATE FUNCTION protect_approved_price_book() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN
   RAISE EXCEPTION 'Price books cannot be deleted' USING ERRCODE = '23514';
 END IF;
 IF OLD.status = 'APPROVED' AND
   (ROW(NEW.id, NEW.workspace_id, NEW.entity_id, NEW.code, NEW.name, NEW.currency, NEW.revision,
        NEW.status, NEW.valid_from, NEW.valid_to, NEW.created_by, NEW.approved_by, NEW.created_at)
      IS DISTINCT FROM
    ROW(OLD.id, OLD.workspace_id, OLD.entity_id, OLD.code, OLD.name, OLD.currency, OLD.revision,
        OLD.status, OLD.valid_from, OLD.valid_to, OLD.created_by, OLD.approved_by, OLD.created_at)
    OR NOT OLD.active OR NEW.active OR NEW.version <> OLD.version + 1) THEN
   RAISE EXCEPTION 'Approved price book is immutable' USING ERRCODE = '23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER price_book_immutable BEFORE UPDATE OR DELETE ON price_books
 FOR EACH ROW EXECUTE FUNCTION protect_approved_price_book();

CREATE FUNCTION protect_approved_price_lines() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE book_status text;
BEGIN
 IF TG_OP <> 'INSERT' THEN
   SELECT status INTO book_status FROM price_books
     WHERE workspace_id=OLD.workspace_id AND entity_id=OLD.entity_id AND id=OLD.price_book_id FOR UPDATE;
   IF book_status = 'APPROVED' THEN
     RAISE EXCEPTION 'Approved price book lines are immutable' USING ERRCODE = '23514';
   END IF;
 END IF;
 IF TG_OP <> 'DELETE' THEN
   SELECT status INTO book_status FROM price_books
     WHERE workspace_id=NEW.workspace_id AND entity_id=NEW.entity_id AND id=NEW.price_book_id FOR UPDATE;
   IF book_status = 'APPROVED' THEN
     RAISE EXCEPTION 'Approved price book lines are immutable' USING ERRCODE = '23514';
   END IF;
   RETURN NEW;
 END IF;
 RETURN OLD;
END $$;
CREATE TRIGGER price_book_line_immutable BEFORE INSERT OR UPDATE OR DELETE ON price_book_lines
 FOR EACH ROW EXECUTE FUNCTION protect_approved_price_lines();
