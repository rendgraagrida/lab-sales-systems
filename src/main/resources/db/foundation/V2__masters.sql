 UNIQUE(workspace_id,id), UNIQUE(workspace_id,entity_id,id), UNIQUE(workspace_id,entity_id,code),
 FOREIGN KEY(workspace_id,entity_id) REFERENCES legal_entities(workspace_id,id)
);
