CREATE TABLE customers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id bigint NOT NULL REFERENCES scenario_workspaces(id),
 code varchar(80) NOT NULL CHECK (length(trim(code)) > 0), name varchar(200) NOT NULL CHECK (length(trim(name)) > 0),
 segment varchar(80) NOT NULL DEFAULT '', territory varchar(80) NOT NULL DEFAULT '', domain varchar(200) NOT NULL DEFAULT '',
 parent_customer_id bigint, active boolean NOT NULL DEFAULT true, created_by bigint NOT NULL REFERENCES app_users(id),
 version bigint NOT NULL DEFAULT 1 CHECK (version > 0), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,id), UNIQUE(workspace_id,code), FOREIGN KEY(workspace_id,parent_customer_id) REFERENCES customers(workspace_id,id), CHECK (parent_customer_id IS NULL OR parent_customer_id <> id)
);
