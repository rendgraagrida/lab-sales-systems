 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id bigint NOT NULL, entity_id bigint NOT NULL,
 code varchar(80) NOT NULL CHECK(length(trim(code)) > 0), name varchar(200) NOT NULL CHECK(length(trim(name)) > 0),
 currency varchar(3) NOT NULL CHECK(currency IN ('EUR','USD')), revision bigint NOT NULL DEFAULT 1 CHECK(revision > 0),
 status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','APPROVED')), active boolean NOT NULL DEFAULT true, valid_from date NOT NULL, valid_to date,
 created_by bigint NOT NULL REFERENCES app_users(id), approved_by bigint REFERENCES app_users(id), version bigint NOT NULL DEFAULT 1 CHECK(version > 0),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
