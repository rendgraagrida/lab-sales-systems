CREATE TABLE crm_contacts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint REFERENCES customers(id),
 first_name text NOT NULL, last_name text NOT NULL, email text NOT NULL, lifecycle text NOT NULL,
 source text NOT NULL DEFAULT 'LOCAL'
);
CREATE TABLE crm_deals (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint REFERENCES customers(id),
 name text NOT NULL, pipeline text NOT NULL, stage text NOT NULL, amount numeric(19,2) NOT NULL,
 currency text NOT NULL, quote_id bigint REFERENCES quotes(id), erp_order_id bigint REFERENCES sales_orders(id),
 source text NOT NULL DEFAULT 'LOCAL'
);
CREATE TABLE crm_imported_companies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, domain text NOT NULL DEFAULT ''
);
ALTER TABLE renewal_intents ADD CONSTRAINT renewal_crm_deal_fk FOREIGN KEY (crm_deal_id) REFERENCES crm_deals(id);
CREATE TABLE crm_external_mappings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, portal_id text NOT NULL, object_type text NOT NULL,
 external_id text NOT NULL, local_id bigint NOT NULL, ownership text NOT NULL, properties jsonb NOT NULL DEFAULT '{}'::jsonb,
 UNIQUE(portal_id,object_type,external_id), UNIQUE(portal_id,object_type,local_id)
);
CREATE TABLE crm_sync_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, operation text NOT NULL, status text NOT NULL,
 started_at timestamptz NOT NULL DEFAULT now(), finished_at timestamptz, processed integer NOT NULL DEFAULT 0,
 errors text NOT NULL DEFAULT ''
);
CREATE TABLE crm_webhook_inbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, portal_id text NOT NULL, subscription_id text NOT NULL,
 event_id text NOT NULL, object_id text NOT NULL, subscription_type text NOT NULL, occurred_at text NOT NULL,
 status text NOT NULL DEFAULT 'PENDING', received_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(portal_id,subscription_id,event_id,object_id,subscription_type,occurred_at)
);
